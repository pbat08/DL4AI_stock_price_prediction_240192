    def create_table(self):
        self.conn.execute('''CREATE TABLE IF NOT EXISTS raw_prices
                             (ticker TEXT, open REAL, high REAL, low REAL, close REAL, volume REAL, date TEXT)''')
    def insert(self, ticker, row):
        self.conn.execute('INSERT INTO raw_prices VALUES (?,?,?,?,?,?,?)', (ticker, *row))
    def fetch(self, ticker):
        return pd.read_sql(f"SELECT * FROM raw_prices WHERE ticker='{ticker}'", self.conn)
    def close(self):
        self.conn.commit()
        self.conn.close()

